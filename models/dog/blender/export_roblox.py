"""Exports the animated Dog (Dog.blend) for Roblox and other engines.

  out/Dog.roblox.fbx      skinned mesh + DogRig skeleton in studs (4.5 studs/m), rest pose, palette texture embedded.
                          File > Import 3D in Studio. (out/Dog.roblox.glb is the same thing as glTF.)
  out/Dog.glb             metres, with the Idle / Walk / Run / Jump actions, for Blender / three.js / Godot / Unity.
  roblox/DogAnimations.luau   the four clips as data for roblox/DogAnimator.luau (no animation upload needed).
  roblox/DogKit.rbxmx     Folder "DogKit" with DogAnimations, DogAnimator, DogController, DogBrain: drag into Studio.
  out/dog_fixture.luau    Blender's evaluated bone poses at sample frames, for tests/animator_test.luau.

Clip data format: per clip and frame, each bone's rotation as a model-space delta D = A * R^-1 (A = animated
armature-space orientation, R = rest orientation) in Blender axes, plus the DogRoot offset in metres. The Roblox
animator maps Blender axes onto the imported skeleton by fitting three bones (DogRoot, Hips, Head), so the clips do
not depend on how the 3D Importer orients, scales or places the bones, nor on each bone's local axis convention.

  blender -b models/dog/blender/Dog.blend --python models/dog/blender/export_roblox.py
"""
import os
import sys
import json
import bpy
from mathutils import Matrix

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import dog_spec as S  # noqa: E402
import animate_dog as A  # noqa: E402

ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "out")
RBX = os.path.join(ROOT, "roblox")
os.makedirs(OUT, exist_ok=True)
os.makedirs(RBX, exist_ok=True)


def num(x, digits=4):
    s = f"{x:.{digits}f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def bone_order(rig):
    return [b.name for b in rig.data.bones]          # parents before children


def sample_clip(rig, name, frames):
    sc = bpy.context.scene
    rig.animation_data.action = bpy.data.actions[name]
    rest_q = {b.name: b.matrix_local.to_quaternion() for b in rig.data.bones}
    rot = {b: [] for b in rest_q}
    root = []
    poses = []
    for fr in frames:
        sc.frame_set(fr)
        frame_pose = {}
        for pb in rig.pose.bones:
            q = pb.matrix.to_quaternion()
            d = q @ rest_q[pb.name].inverted()
            if d.w < 0:
                d.negate()
            rot[pb.name].append(d)
            frame_pose[pb.name] = (pb.head.copy(), q.copy())
        r = rig.pose.bones["DogRoot"]
        root.append(r.head - rig.data.bones["DogRoot"].head_local)
        poses.append(frame_pose)
    rig.animation_data.action = None
    return rot, root, poses


def write_animations(rig):
    order = bone_order(rig)
    lines = [
        "-- Generated by models/dog/blender/export_roblox.py from Dog.blend (animate_dog.py). Do not edit by hand.",
        "-- Per clip and frame: each bone's model-space rotation delta (x, y, z, w) in Blender axes, and the DogRoot",
        "-- offset in metres. DogAnimator maps Blender axes onto the imported skeleton itself (see its header).",
        "return {",
        f"\tfps = {A.FPS},",
        f"\tstudsPerMetre = {S.STUDS_PER_METRE},",
        "\t-- rest bone heads in Blender metres (x, y, z; Z up, the dog faces +Y)",
        "\trest = {",
    ]
    for b in rig.data.bones:
        h = b.head_local
        lines.append(f"\t\t{b.name} = {{ {num(h.x)}, {num(h.y)}, {num(h.z)} }},")
    lines.append("\t},")
    lines.append("\tparents = {")
    for b in rig.data.bones:
        if b.parent:
            lines.append(f'\t\t{b.name} = "{b.parent.name}",')
    lines.append("\t},")
    lines.append("\torder = { " + ", ".join(f'"{n}"' for n in order) + " },")
    lines.append("\tclips = {")
    summary = {}
    fixture = {}
    for name, cfg in A.CLIPS.items():
        n = cfg["frames"]
        frames = list(range(n)) if cfg["loop"] else list(range(n + 1))
        rot, root, poses = sample_clip(rig, name, frames)
        speed_studs = (cfg.get("speed") or 0.0) * S.STUDS_PER_METRE
        lines.append(f"\t\t{name} = {{")
        lines.append(f"\t\t\tframes = {len(frames)},")
        lines.append(f"\t\t\tloop = {'true' if cfg['loop'] else 'false'},")
        lines.append(f"\t\t\tspeed = {num(speed_studs, 3)}, -- studs per second of travel the cycle was made for")
        if name == "Jump":
            lines.append("\t\t\tphysicsLift = true, -- the Humanoid does the jumping: drop the clip's upward root lift")
        if "markers" in cfg:
            mk = ", ".join(f"{k} = {{ {v[0]}, {v[1]} }}" for k, v in cfg["markers"].items())
            lines.append(f"\t\t\tmarkers = {{ {mk} }},")
        lines.append("\t\t\troot = { " + ", ".join(f"{num(v.x, 5)}, {num(v.y, 5)}, {num(v.z, 5)}" for v in root)
                     + " },")
        lines.append("\t\t\trot = {")
        kept = 0
        for b in order:
            qs = rot[b]
            if all(abs(q.w - 1) < 1e-6 for q in qs):
                continue                      # never moves in this clip (DogRoot only translates)
            kept += 1
            flat = ", ".join(f"{num(q.x)}, {num(q.y)}, {num(q.z)}, {num(q.w)}" for q in qs)
            lines.append(f"\t\t\t\t{b} = {{ {flat} }},")
        lines.append("\t\t\t},")
        lines.append("\t\t},")
        summary[name] = {"frames": len(frames), "bones": kept, "speed_studs": round(speed_studs, 2)}
        # fixture: a few frames with Blender's evaluated head position and orientation of every bone
        picks = [0, len(frames) // 3, (2 * len(frames)) // 3, len(frames) - 1]
        fixture[name] = {fr: poses[fr] for fr in picks}
    lines.append("\t},")
    lines.append("}")
    path = os.path.join(RBX, "DogAnimations.luau")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return path, summary, fixture


def write_fixture(rig, fixture):
    def v3(v):
        return f"{{ {num(v.x, 6)}, {num(v.y, 6)}, {num(v.z, 6)} }}"

    def q4(q):
        return f"{{ {num(q.x, 6)}, {num(q.y, 6)}, {num(q.z, 6)}, {num(q.w, 6)} }}"

    out = ["-- Generated by export_roblox.py: Blender's evaluated DogRig pose at sample frames (armature space, metres).",
           "return {", "\trest = {"]
    for b in rig.data.bones:
        out.append(f"\t\t{b.name} = {{ head = {v3(b.head_local)}, rot = {q4(b.matrix_local.to_quaternion())}, "
                   f"len = {num(b.length, 6)} }},")
    out += ["\t},", "\tclips = {"]
    for clip, frames in fixture.items():
        out.append(f"\t\t{clip} = {{")
        for fr, pose in frames.items():
            out.append(f"\t\t\t[{fr}] = {{")
            for b, (h, q) in pose.items():
                out.append(f"\t\t\t\t{b} = {{ head = {v3(h)}, rot = {q4(q)} }},")
            out.append("\t\t\t},")
        out.append("\t\t},")
    out += ["\t},", "}"]
    path = os.path.join(OUT, "dog_fixture.luau")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    return path


def select_only(objs):
    for o in list(bpy.context.scene.objects):
        o.select_set(False)
    for o in objs:
        o.select_set(True)
    bpy.context.view_layer.objects.active = objs[0]


def export_glb_animated(rig, dog):
    """Metres, all four actions, for previews and other engines."""
    select_only([rig, dog])
    path = os.path.join(OUT, "Dog.glb")
    bpy.ops.export_scene.gltf(filepath=path, export_format="GLB", use_selection=True, export_yup=True,
                              export_animations=True, export_animation_mode="ACTIONS", export_force_sampling=True,
                              export_frame_range=False, export_skins=True, export_influence_nb=4,
                              export_all_influences=False, export_def_bones=False, export_materials="EXPORT",
                              export_image_format="AUTO", export_apply=False)
    return path


def bake_studs(rig, dog, k):
    """Scale the rest skeleton and the mesh data by k in place (no object scale left on any node)."""
    select_only([rig])
    bpy.ops.object.mode_set(mode="EDIT")
    for eb in rig.data.edit_bones:
        eb.head = eb.head * k
        eb.tail = eb.tail * k
    bpy.ops.object.mode_set(mode="OBJECT")
    dog.data.transform(Matrix.Scale(k, 4))
    dog.data.update()


def export_roblox(rig, dog):
    # rest pose only: no actions, no NLA, so the importer can't pick up a clip as the rest pose
    rig.animation_data.action = None
    for tr in list(rig.animation_data.nla_tracks):
        rig.animation_data.nla_tracks.remove(tr)
    for pb in rig.pose.bones:
        pb.rotation_quaternion = (1, 0, 0, 0)
        pb.location = (0, 0, 0)
    bake_studs(rig, dog, S.STUDS_PER_METRE)
    select_only([rig, dog])
    fbx = os.path.join(OUT, "Dog.roblox.fbx")
    bpy.ops.export_scene.fbx(filepath=fbx, use_selection=True, object_types={"ARMATURE", "MESH"},
                             apply_unit_scale=True, apply_scale_options="FBX_SCALE_ALL", global_scale=1.0,
                             axis_forward="-Z", axis_up="Y", bake_space_transform=False,
                             use_mesh_modifiers=False, mesh_smooth_type="FACE", use_tspace=False,
                             add_leaf_bones=False, primary_bone_axis="Y", secondary_bone_axis="X",
                             use_armature_deform_only=False, armature_nodetype="NULL",
                             bake_anim=False, path_mode="COPY", embed_textures=True)
    glb = os.path.join(OUT, "Dog.roblox.glb")
    bpy.ops.export_scene.gltf(filepath=glb, export_format="GLB", use_selection=True, export_yup=True,
                              export_animations=False, export_skins=True, export_influence_nb=4,
                              export_def_bones=False, export_materials="EXPORT", export_image_format="AUTO",
                              export_apply=False)
    return fbx, glb


def mesh_stats(dog):
    me = dog.data
    me.calc_loop_triangles()
    lo = [min(v.co[i] for v in me.vertices) for i in range(3)]
    hi = [max(v.co[i] for v in me.vertices) for i in range(3)]
    return {"verts": len(me.vertices), "tris": len(me.loop_triangles),
            "size_xyz": [round(hi[i] - lo[i], 3) for i in range(3)]}


def bundle_kit():
    """Folder DogKit as a Roblox XML model, from the .luau sources (drag the .rbxmx into Studio)."""
    from xml.sax.saxutils import escape
    items = [("ModuleScript", "DogAnimations", "DogAnimations.luau"),
             ("ModuleScript", "DogAnimator", "DogAnimator.luau"),
             ("Script", "DogController", "DogController.client.luau"),
             ("Script", "DogBrain", "DogBrain.server.luau")]
    parts = ['<roblox xmlns:xmime="http://www.w3.org/2005/05/xmlmime" '
             'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
             'xsi:noNamespaceSchemaLocation="http://www.roblox.com/roblox.xsd" version="4">',
             '<Item class="Folder" referent="RBX0"><Properties><string name="Name">DogKit</string></Properties>']
    missing = []
    for i, (cls, name, fn) in enumerate(items, 1):
        p = os.path.join(RBX, fn)
        if not os.path.exists(p):
            missing.append(fn)
            continue
        src = open(p, encoding="utf-8").read()
        extra = ""
        if name == "DogController":
            extra = '<token name="RunContext">2</token>'       # Enum.RunContext.Client
        if cls == "Script":
            extra += '<bool name="Disabled">true</bool>'        # the kit copies stay off; DogSetup enables clones
        parts.append(f'<Item class="{cls}" referent="RBX{i}"><Properties><string name="Name">{name}</string>'
                     f'{extra}<ProtectedString name="Source">{escape(src)}</ProtectedString></Properties></Item>')
    parts.append("</Item></roblox>")
    path = os.path.join(RBX, "DogKit.rbxmx")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(parts) + "\n")
    return path, missing


def main():
    rig = bpy.data.objects["DogRig"]
    dog = bpy.data.objects["Dog"]
    bpy.context.scene.render.fps = A.FPS
    report = {}
    anim_path, report["clips"], fixture = write_animations(rig)
    report["fixture"] = write_fixture(rig, fixture)
    report["glb"] = export_glb_animated(rig, dog)
    report["mesh_m"] = mesh_stats(dog)
    report["roblox"] = export_roblox(rig, dog)          # scales the data: do not save the .blend after this
    report["mesh_studs"] = mesh_stats(dog)
    report["kit"], report["kit_missing"] = bundle_kit()
    report["sizes_kb"] = {os.path.basename(p): round(os.path.getsize(p) / 1024, 1)
                          for p in [anim_path, report["glb"], *report["roblox"], report["kit"]]}
    print("RESULT", json.dumps(report))


if __name__ == "__main__":
    main()
