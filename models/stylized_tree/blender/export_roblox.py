# Exports the StylizedTree (the StylizedTree collection only; the Preview collection never goes out):
#   out/StylizedTree.glb         - metres, for Blender / three.js / Godot / Unity (leaf texture embedded, alpha MASK)
#   out/StylizedTree.roblox.glb  - studs (Roblox 3D Importer, Scale Unit "Stud"), two MeshParts: Trunk, Leaves
# and saves the scene to StylizedTree.blend. roblox/TreeSetup.lua finishes the import in Studio.
import os
import bpy
from mathutils import Matrix

HERE = os.path.dirname(os.path.abspath(__file__)) if "__file__" in dir() else bpy.path.abspath("//")
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "out")
BLEND = os.path.join(HERE, "StylizedTree.blend")
# Same scale as the ClassicHouse (4.5 studs per metre), so the tree and the house fit together.
STUDS_PER_METRE = 4.5


def export(path, scale):
    root = bpy.data.objects["StylizedTree"]
    bpy.ops.object.select_all(action="DESELECT")
    for o in [root] + list(root.children_recursive):
        o.select_set(True)
    bpy.context.view_layer.objects.active = root
    # the scale is baked into the vertices (like the ClassicHouse export), not left on a node, so every MeshPart
    # arrives at its real stud size; a uniform scale leaves the custom (transferred) normals unchanged
    meshes = [o.data for o in root.children if o.type == "MESH"]
    for me in meshes:
        me.transform(Matrix.Scale(scale, 4))
    try:
        bpy.ops.export_scene.gltf(filepath=path, export_format="GLB", use_selection=True, export_yup=True,
                                  export_apply=False, export_normals=True, export_texcoords=True,
                                  export_materials="EXPORT", export_image_format="AUTO", export_animations=False)
    finally:
        for me in meshes:
            me.transform(Matrix.Scale(1 / scale, 4))


def bounds():
    """(min, max) corners of the whole tree in Blender metres (Z up)."""
    from mathutils import Vector
    # from the vertices themselves: Object.bound_box is cached and can be stale right after an export
    pts = [o.matrix_world @ v.co for o in bpy.data.objects["StylizedTree"].children if o.type == "MESH"
           for v in o.data.vertices]
    return [min(p[i] for p in pts) for i in range(3)], [max(p[i] for p in pts) for i in range(3)]


def rbx(v):
    """Blender metres (x, y, z up) -> Roblox studs (x, y up, z): glTF's Y-up axes, times the stud scale."""
    return (v[0] * STUDS_PER_METRE, v[2] * STUDS_PER_METRE, -v[1] * STUDS_PER_METRE)


# The trunk column below the first branch (build_tree.py TRUNK): what players bump into. The trunk mesh itself does
# not collide: Roblox's hull of it would reach out to the branch tips and wall players off ~5 studs from the bark.
COLLIDER = {"axis": (0.06, 0.02), "bottom": 0.0, "top": 2.5, "radius": 0.29}


def write_setup_lua(path):
    lo, hi = bounds()
    centre = [(lo[i] + hi[i]) / 2 for i in range(3)]
    size = rbx([hi[i] - lo[i] for i in range(3)])
    size = (abs(size[0]), size[1], abs(size[2]))
    c = COLLIDER
    col_centre = (c["axis"][0], c["axis"][1], (c["bottom"] + c["top"]) / 2)
    off = rbx([col_centre[i] - centre[i] for i in range(3)])
    ground = rbx([0, 0, 0 - centre[2]])[1]
    lua = f'''-- StylizedTree setup. Generated by models/stylized_tree/blender/export_roblox.py - edit that, not this.
--
-- 1. File > Import 3D > out/StylizedTree.roblox.glb (Scale Unit: Stud, the default). It comes in as a Model with
--    two MeshParts: Trunk (bark, vertex colours) and Leaves (160 double-sided alpha cards, leaf_cluster.png).
-- 2. Select that Model and paste this whole file into the command bar (View > Command Bar), press Enter.
--
-- What it does: scales the tree back to {size[1]:.1f} studs tall if it came in at another size; anchors it; Leaves
-- never collide, touch or block raycasts; the leaf texture goes into a SurfaceAppearance with AlphaMode
-- Transparency (opaque pixels draw fully opaque with depth, so overlapping cards sort correctly: the cutout look);
-- the Trunk mesh does not collide and an invisible cylinder around the trunk column does instead.

local HEIGHT = {size[1]:.3f}                                  -- studs, root tips to crown top
local COLLIDER_OFFSET = Vector3.new({off[0]:.3f}, {off[1]:.3f}, {off[2]:.3f})   -- from the bounding-box centre
local COLLIDER_SIZE = Vector3.new({(c["top"] - c["bottom"]) * STUDS_PER_METRE:.3f}, {2 * c["radius"] * STUDS_PER_METRE:.3f}, {2 * c["radius"] * STUDS_PER_METRE:.3f})  -- cylinder: length on X
local GROUND_OFFSET = {ground:.3f}                            -- ground level (y = 0 in Blender) from the box centre

local model = game.Selection:Get()[1] or workspace:FindFirstChild("StylizedTree")
assert(model and model:IsA("Model"), "Select the imported StylizedTree model first")
local leaves = model:FindFirstChild("Leaves", true)
local trunk = model:FindFirstChild("Trunk", true)
assert(leaves and trunk, "Expected MeshParts named Leaves and Trunk inside the model")

local _, size = model:GetBoundingBox()
if math.abs(size.Y / HEIGHT - 1) > 0.02 then
	model:ScaleTo(model:GetScale() * HEIGHT / size.Y)
	print(("[StylizedTree] rescaled from %.1f to %.1f studs tall"):format(size.Y, HEIGHT))
end
for _, p in model:GetDescendants() do
	if p:IsA("BasePart") then
		p.Anchored = true
	end
end

-- leaves: decoration only
leaves.CanCollide = false
leaves.CanTouch = false
leaves.CanQuery = false
leaves.CastShadow = true
leaves.Transparency = 0
local sa = leaves:FindFirstChildOfClass("SurfaceAppearance")
if not sa then
	sa = Instance.new("SurfaceAppearance")
	local ok, err = pcall(function()
		sa.ColorMap = leaves.TextureID
	end)
	if not ok or leaves.TextureID == "" then
		warn("[StylizedTree] could not copy the leaf texture into a SurfaceAppearance (" .. tostring(err or "no TextureID")
			.. "). Set Leaves > SurfaceAppearance > ColorMap to the uploaded leaf_cluster image by hand.")
	end
	sa.Parent = leaves
end
pcall(function()
	sa.AlphaMode = Enum.AlphaMode.Transparency
end)

-- trunk: the mesh is visual, an invisible cylinder collides
trunk.CanCollide = false
trunk.CanQuery = true
local col = model:FindFirstChild("TrunkCollider") or Instance.new("Part")
col.Name = "TrunkCollider"
col.Shape = Enum.PartType.Cylinder
col.Size = COLLIDER_SIZE
col.Transparency = 1
col.Anchored = true
col.CanCollide = true
col.CastShadow = false
local bbCF = model:GetBoundingBox()
col.CFrame = bbCF * CFrame.new(COLLIDER_OFFSET) * CFrame.Angles(0, 0, math.rad(90))
col.Parent = model
model.PrimaryPart = col
model.WorldPivot = bbCF * CFrame.new(0, GROUND_OFFSET, 0)   -- pivot on the ground at the trunk: drop it on terrain

print(("[StylizedTree] ready: %.1f studs tall, pivot on the ground"):format(HEIGHT))
'''
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write(lua)
    return size


os.makedirs(OUT, exist_ok=True)
export(os.path.join(OUT, "StylizedTree.glb"), 1.0)
export(os.path.join(OUT, "StylizedTree.roblox.glb"), STUDS_PER_METRE)
size_studs = write_setup_lua(os.path.join(ROOT, "roblox", "TreeSetup.lua"))
bpy.ops.wm.save_as_mainfile(filepath=BLEND, relative_remap=True)
lo, hi = bounds()
result = {"size_m_xyz": [round(hi[i] - lo[i], 2) for i in range(3)], "lowest_z": round(lo[2], 2),
          "size_studs": [round(s, 1) for s in size_studs],
          "files": sorted(f for f in os.listdir(OUT) if f.endswith(".glb"))}
